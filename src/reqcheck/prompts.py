def _fill(text: str, open_marker: str, close_marker: str) -> str:
    return text.replace(_OPEN, open_marker).replace(_CLOSE, close_marker)


def requirement_system(open_marker: str, close_marker: str) -> str:
    """System для FR-5: проверка требований по одному (ISO/IEC/IEEE 29148, 5.2.5)."""
    task = """\
## Задача

Проверь каждое требование из пачки по свойствам ISO/IEC/IEEE 29148:2018, п. 5.2.5:
необходимость, уместность (без лишних решений реализации), однозначность, полнота, единичность,
выполнимость, проверяемость, корректность, соответствие терминологии документа.

Во входе два блока данных: сначала ТЕКСТ ДОКУМЕНТА (контекст), затем ПАЧКА требований на проверку
(идентификатор, вид, раздел, текст). Замечания пиши только о требованиях пачки. Документ — чтобы
понимать требование в контексте: определения, модель данных, интерфейсы, ошибки и критерии
приёмки часто описаны в других разделах.

Правило контекста: incomplete, undefined_reference и любое «не указано / не определено» —
только если нужной информации нет НИГДЕ в документе. В explanation напиши, где искал (например,
«в разделах о данных и интерфейсе не нашёл»). Нашёл в другом разделе — замечания нет."""
    parts = [
        _ROLE.format(version=PROMPT_VERSION),
        task,
        _DATA_RULES,
        _REQ_TYPES,
        _QUOTES,
        _PRECISION,
        _REQ_EXAMPLE,
    ]
    return _fill("\n\n".join(parts), open_marker, close_marker)


def set_system(open_marker: str, close_marker: str, *, focus: str) -> str:
    """System для одного узкого вызова FR-6: focus из SET_FOCUSES."""
    focus_text = _FOCUS_TEXT[focus]
    if focus != "acceptance":
        focus_text += "\n\n" + _NO_LINKS
    parts = [
        _ROLE.format(version=PROMPT_VERSION),
        _SET_TASK,
        _DATA_RULES,
        focus_text,
        _QUOTES,
        _PRECISION,
    ]
    return _fill("\n\n".join(parts), open_marker, close_marker)


