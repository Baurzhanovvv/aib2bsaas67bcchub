def _fill(text: str, open_marker: str, close_marker: str) -> str:
    return text.replace(_OPEN, open_marker).replace(_CLOSE, close_marker)


def requirement_system(open_marker: str, close_marker: str) -> str:
    """System для FR-5: проверка требований по одному (ISO/IEC/IEEE 29148, 5.2.5)."""
    task = """\
## Задача

Проверь каждое требование из входа по свойствам ISO/IEC/IEEE 29148:2018, п. 5.2.5: необходимость,
уместность (без лишних решений реализации), однозначность, полнота, единичность, выполнимость,
проверяемость, корректность, соответствие терминологии документа. Каждое требование дано с
идентификатором, видом и разделом; другие требования входа — контекст, а не предмет повтора."""
    parts = [
        _ROLE.format(version=PROMPT_VERSION),
        task,
        _DATA_RULES,
        _REQ_TYPES,
        _QUOTES,
        _PRECISION,
        _REQ_EXAMPLE,
    ]
    return _fill("\n\n".join(parts), open_marker, close_marker)


def set_system(open_marker: str, close_marker: str, *, has_acceptance: bool) -> str:
    """System для FR-6: проверка набора (5.2.6, IEEE 830 4.3) и трассировка."""
    parts = [
        _ROLE.format(version=PROMPT_VERSION),
        _SET_TASK,
        _DATA_RULES,
        _SET_TYPES,
        _TRACE_WITH if has_acceptance else _TRACE_WITHOUT,
        _QUOTES,
        _PRECISION,
        _SET_EXAMPLE,
    ]
    return _fill("\n\n".join(parts), open_marker, close_marker)


def requirement_user(wrapped_requirements: str) -> str:
    return (
        "Проверь требования в блоке ниже. Каждое начинается строкой "
        "«[R-NNN] вид: …; раздел: …», дальше — его дословный текст.\n\n"
        f"{wrapped_requirements}"
    )


